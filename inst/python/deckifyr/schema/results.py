"""Versioned `--json` result payloads (issue #85).

Machine callers -- the R facade, CI, a workspace launcher -- read the
CLI's `--json` output. Until now its shape was implicit in `cli.py`'s
handlers, with no way to detect a change. These models are the contract:

* every success and every error payload carries `result_version`
  (`RESULT_VERSION`), bumped only for a change an existing consumer could
  not ignore -- adding a key is *not* one, so consumers must tolerate
  unknown keys;
* `validate`, `build`, `preview` and the error envelope have their own
  model (published as JSON Schema under `schemas/results/`, generated by
  `scripts/generate_json_schemas.py`, and checked in tests against real
  CLI output); every other command's payload is only promised to match
  `OkResult` (`status` + `result_version`, extra keys allowed).

Existing keys (`output`, `manifest`, `previews`, `preview_pdf`,
`warning_count`, ...) are unchanged, so the R facade and the web job
manager keep working untouched.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

RESULT_VERSION = 1


class _Model(BaseModel):
    # Strict on purpose for the commands that have a published schema: a new
    # key must be added here (and the schema regenerated), not slipped in.
    model_config = ConfigDict(extra="forbid")


class WarningEntry(_Model):
    code: str = Field(description="Stable identifier for the kind of warning (e.g. W_MULTI_FIGURE).")
    message: str = Field(description="Human-readable text.")
    slide: str | None = Field(description="Id of the slide it came from, or null for a build-level warning.")
    element: str | None = Field(description="Id of the element it came from, or null.")


class ArtifactEntry(_Model):
    kind: Literal["pptx", "manifest", "preview", "preview_pdf"] = Field(
        description="What the file is."
    )
    path: str = Field(description="Absolute path of the file.")
    sha256: str = Field(description="SHA-256 of the file's bytes, so callers can record provenance without re-hashing.")


class DependencyEntry(_Model):
    name: str
    display_name: str
    install_url: str


class OkResult(BaseModel):
    """What every successful `--json` payload promises, whatever the command."""

    model_config = ConfigDict(extra="allow")

    status: str = Field(description='"ok" (the `serve` command reports "stopped").')
    result_version: int = Field(description="Version of the result schema; see deckifyr.schema.results.")


class ValidateResult(_Model):
    status: Literal["ok"]
    result_version: Literal[1]
    valid: bool
    presentation: str
    slide_count: int
    layout_count: int
    schema_version: str
    warnings: list[WarningEntry] = Field(
        description="Validation warnings. Reserved: validation has no warning producers today, so this is always empty."
    )


class BuildResultPayload(_Model):
    status: Literal["ok"]
    result_version: Literal[1]
    output: str
    manifest: str | None = Field(description="Manifest path, or null when `build.manifest` is not configured.")
    slide_count: int
    warning_count: int = Field(description="len(warnings); kept for compatibility.")
    warnings: list[WarningEntry] = Field(
        description="Every build warning, whether or not a manifest is written."
    )
    previews: list[str]
    preview_pdf: str | None
    artifacts: list[ArtifactEntry] = Field(
        description="The output, manifest, previews and preview PDF with SHA-256 hashes."
    )


class PreviewResultPayload(_Model):
    status: Literal["ok"]
    result_version: Literal[1]
    output: str
    previews: list[str]
    preview_pdf: str | None
    slide_count: int
    warning_count: int
    warnings: list[WarningEntry]
    artifacts: list[ArtifactEntry]


class ErrorResult(_Model):
    status: Literal["error"]
    result_version: Literal[1]
    code: str = Field(description="Stable error code (deckifyr.schema.errors.ErrorCode).")
    message: str
    dependency: DependencyEntry | None = Field(
        default=None, description="Present only for E_MISSING_DEPENDENCY."
    )


# Published schema name -> model. Single registry for the generator, the
# staleness test and the real-output tests.
RESULT_MODELS: dict[str, type[BaseModel]] = {
    "ok": OkResult,
    "validate": ValidateResult,
    "build": BuildResultPayload,
    "preview": PreviewResultPayload,
    "error": ErrorResult,
}
